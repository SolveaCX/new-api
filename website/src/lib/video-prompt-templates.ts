export const VIDEO_MODEL_IDS = Object.freeze(Object.keys(VIDEO_MODEL_POSTER_SETS));

/**
 * Model IDs with a reviewed six-profession CDN batch.  Keep this separate
 * from `VIDEO_MODEL_IDS`: the latter is a backwards-compatible registry of
 * every model that has legacy poster references, while this list is the
 * allowlist for profession-labelled cards.  A legacy clip must never be
 * promoted to a profession card just because it occupies the same array
 * position.
 */
export const VIDEO_PROFESSION_MODEL_IDS = Object.freeze(Object.keys(VIDEO_PROFESSION_SETS));

export function getVideoPromptTemplateFallbackPosters(modelId: string): readonly string[] {
  const slug = normalizeVideoModelId(modelId);
  const posters = VIDEO_PROFESSION_POSTER_SETS[slug];
  if (!posters) return [];
  return VIDEO_PROFESSION_IDS.map((professionId) => posters[professionId]);
}

/**
 * Return a packaged first frame for every reviewed profession clip. The file
 * name includes both the profession and model so a failed CDN request cannot
 * silently show a neighbouring profession or another model's sample.
 */
export function getVideoPromptTemplateLocalFallbackPosters(modelId: string): readonly string[] {
  const resolvedModelId = resolveVideoProfessionModelId(modelId);
  if (!resolvedModelId) return [];
  return VIDEO_PROFESSION_IDS.map(
    (professionId) => `${VIDEO_LOCAL_FALLBACK_BASE}/${professionId}/${resolvedModelId}.jpg`,
  );
}

/** Resolve the packaged poster paired with one exact profession clip. */
export function getVideoPromptTemplateLocalFallbackPoster(
  modelId = "",
  professionId?: VideoProfessionId,
): string | undefined {
  if (!professionId) return undefined;
  const index = VIDEO_PROFESSION_IDS.indexOf(professionId);
  return index >= 0 ? getVideoPromptTemplateLocalFallbackPosters(modelId)[index] : undefined;
}

/** Return six profession templates with one stable media binding per card. */
export function getVideoPromptTemplates(modelId: string, locale: Locale = "en"): readonly VideoPromptTemplate[] {
  const slug = normalizeVideoModelId(modelId);
  // Only a reviewed profession batch can back the six profession cards.  Do
  // not fall back to the legacy model clip tuple: those clips were authored
  // for the old generic/industry examples and have no profession metadata.
  const videos = VIDEO_PROFESSION_SETS[slug];
  const localizedCopy = VIDEO_PROFESSION_LOCALE_COPY[locale] ?? VIDEO_PROFESSION_LOCALE_COPY.en;
  const legacyCopy = LEGACY_VIDEO_PROMPT_LOCALE_COPY[locale];
  const posters = VIDEO_PROFESSION_POSTER_SETS[slug];
  const modelPrompts = VIDEO_MODEL_ENGLISH_PROMPTS[slug];
  if (!videos) return [];

  const cards = VIDEO_PROMPT_TEMPLATES.map((template) => {
    const professionId = template.professionId;
    const video = videos[professionId];
    const label = localizedCopy.labels[professionId] ?? legacyCopy?.labels[template.id] ?? template.label;
    // Prompt bodies are canonical English and are keyed to the reviewed
    // model clip.  Localized maps remain available for legacy serialization,
    // but must never replace the copy displayed on a model page.
    const prompt = modelPrompts?.[professionId] ?? template.prompt;
    if (!video || !label || !prompt) return null;
    return {
      ...template,
      label,
      // Only a same-source poster is allowed here. If a model has no reviewed
      // poster, leave it empty rather than pairing a legacy industry image.
      poster: posters?.[professionId] ?? "",
      video,
      prompt,
    };
  });

  return cards.every((card): card is VideoPromptTemplate => card !== null) ? cards : [];
}

/** Localize a shared video brief when a configured page stores its source text. */
export function localizeVideoPromptText(prompt: string, _locale: Locale): string {
  // Reviewed prompts are already canonical English.  Return them unchanged
  // so a non-English route cannot substitute a translated or generic brief.
  for (const promptSet of Object.values(VIDEO_MODEL_ENGLISH_PROMPTS)) {
    if (Object.values(promptSet).some((candidate) => candidate === prompt)) return prompt;
  }

  const baseTemplate = VIDEO_PROMPT_TEMPLATES.find((template) => prompt.startsWith(template.prompt));
  if (baseTemplate) return baseTemplate.prompt;

  // Legacy configured cards may contain one of the old localized briefs. Map
  // those serialized values back to the canonical English base prompt.
  for (const copy of Object.values(VIDEO_PROFESSION_LOCALE_COPY)) {
    const entry = Object.entries(copy.prompts).find(([, value]) => value && prompt.startsWith(value));
    if (entry) {
      const template = VIDEO_PROMPT_TEMPLATES.find((candidate) => candidate.id === entry[0]);
      if (template) return template.prompt;
    }
  }

  const generic = prompt.match(/^Create a short product video with (.+?): *clear subject motion, realistic lighting, stable camera, and production-ready framing\.?$/i);
  return generic
    ? `Create a short video with ${generic[1].trim()}: clear subject motion, realistic lighting, stable camera, and production-ready framing.`
    : prompt;
}

/**
 * Locale-aware starter for video Playground forms. The model id remains a
 * technical literal; the surrounding instruction follows the selected locale.
 */
export function getVideoPlaygroundPrompt(modelId: string, _locale: Locale = "en", displayName = modelId): string {
  // Keep the Playground input synchronized with the first reviewed gallery
  // card.  This is intentionally English on every locale route.
  const reviewedStarter = getVideoPromptTemplates(modelId, "en")[0]?.prompt;
  if (reviewedStarter) return reviewedStarter;
  return `Create a short video with ${displayName}: clear subject motion, realistic lighting, stable camera, and production-ready framing.`;
}
